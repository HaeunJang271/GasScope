export interface Hotspot {
  rule: string;
  line: number;
  estimatedGas: number;
  allocRisk: string;
  suggestion: string;
  before: string;
  after: string;
}
export interface Call { target: string; line: number; crossRealm: boolean }
export interface FunctionProfile {
  id: string;
  name: string;
  file: string;
  line: number;
  exported: boolean;
  estimatedGas: number;
  hotspots: Hotspot[];
  calls: Call[];
}
export interface Report {
  mode: string;
  totalGas: number;
  functions: FunctionProfile[];
  note?: string;
  tests?: { package: string; passed: boolean; timingMs: Record<string, number>; gasUsed?: Record<string, number> }[];
}

type Analyzer = (sources: string) => { report?: string; error?: string };
declare global {
  interface Window {
    Go: new () => { importObject: WebAssembly.Imports; run: (instance: WebAssembly.Instance) => Promise<void> };
    analyzeGasScope?: Analyzer;
  }
}

let ready: Promise<void> | undefined;
export async function analyze(sources: Record<string, string>): Promise<Report> {
  ready ??= (async () => {
    const base = import.meta.env.BASE_URL;
    if (!window.Go) {
      await new Promise<void>((resolve, reject) => {
        const script = document.createElement('script');
        script.src = base + 'wasm_exec.js';
        script.onload = () => resolve();
        script.onerror = () => reject(new Error('Unable to load the Go runtime.'));
        document.head.append(script);
      });
    }
    const go = new window.Go();
    const response = await fetch(base + 'profile.wasm');
    if (!response.ok) throw new Error('Unable to load the GasScope analyzer.');
    const { instance } = await WebAssembly.instantiate(await response.arrayBuffer(), go.importObject);
    void go.run(instance).catch(console.error);
    if (!window.analyzeGasScope) throw new Error('GasScope did not initialize.');
  })().catch(error => { ready = undefined; throw error; });
  await ready;
  const result = window.analyzeGasScope!(JSON.stringify(sources));
  if (!result.report) throw new Error(result.error ?? 'Analysis failed.');
  return JSON.parse(result.report);
}

export function readReport(text: string): Report {
  const data: Report = JSON.parse(text);
  if (!data || !Number.isFinite(data.totalGas) || data.totalGas < 0 || !Array.isArray(data.functions) ||
      data.functions.some(f => !f || typeof f.id !== 'string' || typeof f.name !== 'string' ||
        typeof f.file !== 'string' || !Number.isInteger(f.line) || !Number.isFinite(f.estimatedGas) ||
        !Array.isArray(f.calls) || f.calls.some(c => !c || typeof c.target !== 'string' || !Number.isInteger(c.line)) ||
        !Array.isArray(f.hotspots) || f.hotspots.some(h => !h || typeof h.rule !== 'string' ||
          typeof h.suggestion !== 'string' || typeof h.before !== 'string' || typeof h.after !== 'string' ||
          typeof h.allocRisk !== 'string' || !Number.isInteger(h.line) || !Number.isFinite(h.estimatedGas)))) {
    throw new Error('Select a GasScope report generated by the CLI.');
  }
  return data;
}

